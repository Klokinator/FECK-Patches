// Generates FECK's schemas/patches/skill-system-bins.json: addresses, lengths and file names of each skill system's BINF lines. No bytes, no hashes.
// Zero dependencies: node _tools/gen-skill-system-bins.mjs [--check]   (--check exits 1 when the file on disk is stale; otherwise it is rewritten)
// Each version id comes from skill-systems.json; the folder is that entry's "source", the patch is the PATCH file in its installer folder.
// One entry per BINF line, in the PATCH file's line order (duplicates kept, not sorted). UPDATE_UNINSTALL lines are skipped.
// Any BIN, BINP, BINAP, $FREEAREA or macro-address line stops the run: the generator only understands plain BINF:0x<hex>=<file> lines.
import { readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const feck = resolve(root, "..", "Fire-Emblem-Creation-Kit");
const schemas = join(feck, "schemas", "patches");
const outPath = join(schemas, "skill-system-bins.json");
const VERSIONS = [{ id: "cskillsys-330lts", patch: "installer/PATCH_CSkillSys330LTS.txt" }];

const fail = (m) => { console.error("gen-skill-system-bins: " + m); process.exit(2); };
const systems = JSON.parse(readFileSync(join(schemas, "skill-systems.json"), "utf8"));
const out = {
  about: "Generated by FECK-Patches/_tools/gen-skill-system-bins.mjs; addresses and lengths only.",
  versions: {},
};

for (const v of VERSIONS) {
  const entry = systems.versions.find((e) => e.id === v.id);
  if (!entry) fail(`${v.id} is not in skill-systems.json`);
  const dir = resolve(root, "..", entry.source);
  const patchPath = join(dir, v.patch);
  if (!existsSync(patchPath)) fail(`missing ${patchPath}`);
  const bins = [];
  const lines = readFileSync(patchPath, "utf8").replace(/^﻿/, "").split(/\r?\n/);
  lines.forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith("//") || line.startsWith("UPDATE_UNINSTALL")) return;
    const key = line.split("=")[0];
    if (/^BIN/i.test(key) && !/^BINF:/i.test(key)) fail(`line ${i + 1}: unsupported ${key}`);
    if (/\$FREEAREA/i.test(line)) fail(`line ${i + 1}: $FREEAREA`);
    if (!/^BINF:/i.test(line)) return;
    const m = /^BINF:(0x[0-9A-Fa-f]+)=(.+)$/.exec(line);
    if (!m) fail(`line ${i + 1}: cannot read "${line}" (macro or odd address)`);
    const file = m[2].trim();
    const bp = join(dirname(patchPath), file);
    if (!existsSync(bp)) fail(`line ${i + 1}: missing ${file}`);
    bins.push({ address: m[1], length: statSync(bp).size, file });
  });
  out.versions[v.id] = { patch: v.patch, bins };
  console.log(`${v.id}: ${bins.length} entries, length sum ${bins.reduce((a, b) => a + b.length, 0)}`);
}

const text = JSON.stringify(out, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== text) { console.error("skill-system-bins.json is stale"); process.exit(1); }
} else writeFileSync(outPath, text);
